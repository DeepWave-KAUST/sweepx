"""Perceptually-tuned colormaps for seismic data, embedded as Python literals.

Two custom LUTs are bundled directly here (no .npy assets):

* ``sweep_vp`` — non-linear rainbow ramp tuned for marine sediment Vp in the
  1500-6000 m/s range. Bottom of the LUT sits at pure white so a
  water-velocity-clip rendering does not visually drown the model. Used by
  ``plot_vp`` (and any caller that defaults to ``VP_CMAP``).
* ``sweep_image`` — dark-red ← white → black diverging map tuned for
  illumination-normalised RTM / kernel images. Saturates cleanly at the
  ±99.5-percentile clip used by ``plot_kernel`` / RTM viz helpers.
  ``IMAGE_CMAP`` (and the legacy alias ``KERNEL_CMAP``) default to this.

Both are registered as matplotlib colormaps at import time so any string
lookup (e.g. ``plt.get_cmap("sweep_vp")``) works without extra wiring. The
``sweep_`` prefix avoids collisions with matplotlib built-ins and follows
the cmocean / cmc third-party convention.
"""

