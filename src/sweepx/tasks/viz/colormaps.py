def _register(name: str, lut: tuple[tuple[float, float, float], ...]) -> None:
    """Idempotently register a ListedColormap on the global matplotlib registry."""
    if name in _mpl_colormaps:
        return
    _mpl_colormaps.register(ListedColormap(lut, name=name))

_register("sweep_vp", _SWEEP_VP_LUT)
_register("sweep_image", _SWEEP_IMAGE_LUT)

# === Public colormap aliases ===
# Velocity / impedance models: the bundled ``sweep_vp`` LUT is the new
# default. Set to "viridis" if you want the perceptually-uniform fallback.
